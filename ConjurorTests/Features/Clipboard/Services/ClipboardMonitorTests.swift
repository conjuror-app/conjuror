import Testing

@testable import Conjuror

@MainActor
@Suite("Clipboard monitor")
struct ClipboardMonitorTests {
  @Test("Records text copied after it starts, but not what was already there")
  func testRecordsNewCopies() {
    let pasteboard = FakePasteboard(text: "before")
    let recorder = CaptureRecorder()
    let monitor = makeMonitor(pasteboard: pasteboard, recorder: recorder)
    monitor.start()
    defer { monitor.stop() }

    monitor.checkForChanges()
    pasteboard.copy("after")
    monitor.checkForChanges()
    monitor.checkForChanges()

    #expect(recorder.texts == ["after"])
  }

  @Test("Skips secret, temporary, and generated content")
  func testSkipsMarkedContent() {
    let pasteboard = FakePasteboard()
    let recorder = CaptureRecorder()
    let monitor = makeMonitor(pasteboard: pasteboard, recorder: recorder)

    for marker in [
      "org.nspasteboard.ConcealedType",
      "org.nspasteboard.TransientType",
      "org.nspasteboard.AutoGeneratedType",
    ] {
      pasteboard.copy("secret", extraTypes: [marker])
      monitor.checkForChanges()
    }

    #expect(recorder.texts.isEmpty)
    #expect(pasteboard.textReadCount == 0)
  }

  @Test("Skips copies from excluded apps without reading them")
  func testSkipsExcludedApps() {
    let pasteboard = FakePasteboard()
    let recorder = CaptureRecorder()
    let monitor = makeMonitor(
      pasteboard: pasteboard,
      recorder: recorder,
      source: ClipboardSource(name: "1Password", bundleIdentifier: "com.1password.1password")
    )

    pasteboard.copy("hunter2")
    monitor.checkForChanges()

    #expect(recorder.texts.isEmpty)
    #expect(pasteboard.textReadCount == 0)
  }

  @Test("Skips blank text and copied files")
  func testSkipsBlankTextAndFiles() {
    let pasteboard = FakePasteboard()
    let recorder = CaptureRecorder()
    let monitor = makeMonitor(pasteboard: pasteboard, recorder: recorder)

    pasteboard.copy("  \n\t")
    monitor.checkForChanges()
    pasteboard.copy("Report.pdf", extraTypes: ["public.file-url"])
    monitor.checkForChanges()

    #expect(recorder.texts.isEmpty)
  }

  @Test("Records the app that was in front")
  func testRecordsSource() {
    let pasteboard = FakePasteboard()
    let recorder = CaptureRecorder()
    let source = ClipboardSource(name: "Safari", bundleIdentifier: "com.apple.Safari")
    let monitor = makeMonitor(pasteboard: pasteboard, recorder: recorder, source: source)

    pasteboard.copy("https://example.com")
    monitor.checkForChanges()

    #expect(recorder.sources == [source])
  }

  private func makeMonitor(
    pasteboard: FakePasteboard,
    recorder: CaptureRecorder,
    source: ClipboardSource? = nil
  ) -> ClipboardMonitor {
    ClipboardMonitor(
      pasteboard: pasteboard,
      currentSource: { source },
      onCapture: { text, source in recorder.record(text, source: source) }
    )
  }
}

@MainActor
private final class FakePasteboard: ClipboardPasteboard {
  private(set) var changeCount = 0
  private(set) var typeIdentifiers = [String]()
  private(set) var textReadCount = 0
  private var storedText: String?

  init(text: String? = nil) {
    if let text { copy(text) }
  }

  func copy(_ text: String, extraTypes: [String] = []) {
    storedText = text
    typeIdentifiers = ["public.utf8-plain-text"] + extraTypes
    changeCount += 1
  }

  func text() -> String? {
    textReadCount += 1

    return storedText
  }
}

@MainActor
private final class CaptureRecorder {
  private(set) var texts = [String]()
  private(set) var sources = [ClipboardSource?]()

  func record(_ text: String, source: ClipboardSource?) {
    texts.append(text)
    sources.append(source)
  }
}

#!/usr/bin/env node

/** Generate the checked-in emoji catalog from Unicode's emoji-test data. */

import { spawnSync } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname } from "node:path";

const version = "latest";
const url = `https://unicode.org/Public/emoji/${version}/emoji-test.txt`;
const output = "Conjuror/Features/Emoji/Models/EmojiCatalog.gen.swift";

const response = await fetch(url);
if (!response.ok) {
  throw new Error(`Could not download ${url}: ${response.status} ${response.statusText}`);
}

const entries = [];
let category = "";
for (const line of (await response.text()).split("\n")) {
  if (line.startsWith("# group: ")) {
    category = line.slice("# group: ".length).trim();
    continue;
  }

  const match = line.match(
    /^([0-9A-F ]+)\s*; fully-qualified\s*#\s*\S+\s+E[0-9.]+\s+(.+)$/,
  );
  if (!match) continue;

  entries.push({
    value: match[1]
      .trim()
      .split(/\s+/)
      .map((codePoint) => String.fromCodePoint(Number.parseInt(codePoint, 16)))
      .join(""),
    name: match[2].trim(),
    category,
  });
}

const lines = [
  `// Generated by scripts/generate_emoji.js from Unicode Emoji ${version}. Do not edit.`,
  "",
  "enum EmojiData {",
  '  static let raw = #"""',
  ...entries.map(({ value, name, category }) => `  ${value}|${name}|${category}`),
  '  """#',
  "}",
  "",
];

await mkdir(dirname(output), { recursive: true });
await writeFile(output, lines.join("\n"));
const format = spawnSync(
  "swift",
  [
    "format",
    "format",
    "--configuration",
    ".swift-format",
    "--in-place",
    output,
  ],
  { stdio: "inherit" },
);
if (format.error) throw format.error;
if (format.status !== 0) {
  throw new Error(`swift format exited with status ${format.status}`);
}
console.log(`Generated ${entries.length} emoji in ${output}`);
